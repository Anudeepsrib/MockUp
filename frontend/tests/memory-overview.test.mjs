import assert from 'node:assert/strict';
import {isRecallable,summarizeMemories} from '../src/lib/memory.ts';

const fact=(id,extra={})=>({id,type:'Observation',title:id,content:id,source:'service',confidence:95,confirmed:true,savedAt:'2026-01-01T00:00:00Z',...extra});
const approved=fact('approved');
const draft=fact('draft',{confirmed:false,savedAt:'2026-11-01T00:00:00Z'});
const blocked=fact('blocked',{type:'Learned pattern',sourceFactIds:['draft'],savedAt:'2026-11-02T00:00:00Z'});
const pattern=fact('pattern',{type:'Learned pattern',sourceFactIds:['approved']});
const missing=fact('missing',{sourceFactIds:['absent']});
const retired=fact('retired',{state:'invalidated',source:'retired-source',savedAt:'2026-12-01T00:00:00Z'});
const records=[approved,draft,blocked,pattern,missing,retired];
const summary=summarizeMemories(records);
assert.equal(summary.readyCount,2,'An approved pattern with unapproved evidence is held back');
assert.equal(summary.reviewCount,3);
assert.equal(summary.patternCount,1);
assert.equal(summary.sourceCount,1,'Retired sources are excluded');
assert.equal(summary.reviewNext.id,'draft','Review evidence before a newer blocked pattern');
assert.equal(summary.takeaways[0].id,'blocked','Recent learning appears first');
assert.ok(!summary.takeaways.includes(retired));
assert.equal(isRecallable(blocked,records),false);
assert.equal(isRecallable(missing,records),false);
assert.equal(isRecallable(pattern,records),true);
const cycle=[fact('a',{sourceFactIds:['b']}),fact('b',{sourceFactIds:['a']})];
assert.equal(summarizeMemories(cycle).readyCount,0,'Cyclic evidence cannot become reusable');
const duplicate=fact('duplicate',{content:' APPROVED ',savedAt:'2026-11-03T00:00:00Z'});
assert.equal(summarizeMemories([approved,duplicate]).takeaways.length,1,'Repeated text is shown once without deleting stored records');
assert.equal(summarizeMemories([approved,duplicate]).readyCount,2);
assert.equal(summarizeMemories([fact('note',{type:'Session context'})]).takeaways.length,1);
assert.deepEqual(summarizeMemories([]),{readyCount:0,reviewCount:0,patternCount:0,sourceCount:0,reviewNext:undefined,takeaways:[]});
assert.equal(approved.confirmed,true,'Summaries never mutate records');
console.log('Memory overview self-check passed: evidence eligibility, review order, recent learning, and empty state.');
